/**
 * Render an icon to an inline <svg> string.
 * @param {string} name  key in ICONS
 * @param {number} [size=24]
 * @param {string} [cls='']  extra class names
 * @param {string} [extra='']  extra attributes (e.g. 'aria-hidden="true"')
 */
function icon(name, size = 24, cls = '', extra = '') {
  const it = ICONS[name];
  if (!it) return '';
  const vb = it.vb || '0 0 24 24';
  const attrs = it.fill
    ? `fill="currentColor" stroke="none"`
    : `fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round"`;
  const classAttr = cls ? ` class="${cls}"` : '';
  const extraAttr = extra ? ` ${extra}` : '';
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}" width="${size}" height="${size}"` +
    `${classAttr}${extraAttr} ${attrs} aria-hidden="true" focusable="false">${it.d}</svg>`
  );
}

function hasIcon(name) {
  return Object.prototype.hasOwnProperty.call(ICONS, name);
}

